import SwiftUI

/// The "GovernAI" assistant panel docked on the right. Matches the Figma:
/// white header + tabs + breadcrumb over a tinted (#F5F8F9) content area with
/// white bordered summary cards.
struct GovernAIPanel: View {
    let onClose: () -> Void
    @State private var tab = 1   // 0 = Smart Assist, 1 = Insights

    private let contentBg = Color(hex: "#F5F8F9")
    private let cardBorder = Color(hex: "#E2E2E5")
    private let ink = Color(hex: "#242628")
    private let purple = Color(hex: "#7C5CFC")

    var body: some View {
        VStack(spacing: 0) {
            header
            tabBar
            breadcrumb
            content
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(DS.ColorToken.background)
        .ignoresSafeArea(edges: .bottom)
    }

    // MARK: Header

    private var header: some View {
        HStack(spacing: DS.Space.xs) {
            Image("ic_ai").resizable().scaledToFit().frame(width: 22, height: 22)
            Text("GovernAI").font(.custom(DS.Typeface.semibold, size: 20)).foregroundStyle(ink)
                .lineLimit(1).fixedSize()
            Spacer(minLength: DS.Space.sm)
            PlainIconButton(symbol: "ellipsis", size: 28, glyph: 18)
            PlainIconButton(symbol: "arrow.up.left.and.arrow.down.right", size: 28, glyph: 15)
            // Reserved slot for the shared floating GovernAI button (same place/size
            // as the closed state); the floating button overlays this spot.
            Color.clear.frame(width: 46, height: 46)
        }
        .padding(.horizontal, DS.Space.smd)
        .frame(height: 94)
        .background(DS.ColorToken.background)
    }

    // MARK: Tabs

    private var tabBar: some View {
        HStack(spacing: 0) {
            tabButton("Smart Assist", 0)
            tabButton("Insights", 1)
            Spacer()
        }
        .padding(.horizontal, DS.Space.md)
        .background(DS.ColorToken.background)
        .overlay(alignment: .bottom) { Rectangle().fill(DS.ColorToken.border).frame(height: 1) }
    }

    private func tabButton(_ title: String, _ index: Int) -> some View {
        Button { tab = index } label: {
            VStack(spacing: DS.Space.sm) {
                Text(title).dsText(DS.Text.bodySmEmph, color: ink)
                Rectangle().fill(tab == index ? DS.ColorToken.primaryStrong : .clear).frame(height: 2)
            }
            .padding(.horizontal, DS.Space.smd)
        }
        .buttonStyle(.plain)
        .frame(height: 28)
    }

    // MARK: Breadcrumb

    private var breadcrumb: some View {
        HStack(spacing: DS.Space.smd) {
            Image(systemName: "chevron.left").font(.system(size: 12, weight: .semibold)).foregroundStyle(ink)
            Text("Smart Summary").dsText(DS.Text.bodySmEmph, color: ink)
            Spacer()
        }
        .padding(.horizontal, DS.Space.md)
        .frame(height: 40)
        .background(DS.ColorToken.background)
    }

    // MARK: Content

    private var content: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: DS.Space.md) {
                metaRow
                Text("Executive Summary").font(.custom(DS.Typeface.semibold, size: 18)).foregroundStyle(ink)
                card {
                    topic("Financial reports")
                    topic("Strategic updates")
                    Divider().overlay(DS.ColorToken.border)
                    HStack(spacing: DS.Space.xs) {
                        Image(systemName: "chevron.down").font(.system(size: 12, weight: .semibold))
                        Text("Show more").dsText(DS.Text.bodyMdEmph, color: ink)
                    }
                }
                Text("Detailed Summary").font(.custom(DS.Typeface.semibold, size: 18)).foregroundStyle(ink)
                card {
                    document("Financial reports", sub: "Document — Q4 2025 Consolidated Financial Statements")
                    document(nil, sub: "Subtopic of document")
                    document(nil, sub: nil)
                }
                card {
                    document("FY2025 Budget vs Actual Analysis", sub: nil)
                }
                Color.clear.frame(height: 24)
            }
            .padding(DS.Space.lg)
        }
        .scrollIndicators(.hidden)
        .background(contentBg)
    }

    private var metaRow: some View {
        HStack {
            Text("Last updated on Apr 30, 2026, 11:24:40 AM")
                .font(.custom(DS.Typeface.regular, size: 10)).foregroundStyle(Color(hex: "#676767"))
            Spacer()
            HStack(spacing: DS.Space.xs) {
                Image(systemName: "sparkles").font(.system(size: 11)).foregroundStyle(Color(hex: "#5D5E61"))
                Text("Generated by AI").font(.custom(DS.Typeface.regular, size: 11)).foregroundStyle(Color(hex: "#5D5E61"))
            }
        }
    }

    @ViewBuilder
    private func card<C: View>(@ViewBuilder _ body: () -> C) -> some View {
        VStack(alignment: .leading, spacing: DS.Space.md) { body() }
            .padding(DS.Space.lg)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(DS.ColorToken.background, in: RoundedRectangle(cornerRadius: DS.Radius.lg))
            .overlay(RoundedRectangle(cornerRadius: DS.Radius.lg).stroke(cardBorder, lineWidth: 1))
    }

    private func topic(_ heading: String) -> some View {
        VStack(alignment: .leading, spacing: DS.Space.sm) {
            Text(heading).font(.custom(DS.Typeface.semibold, size: 18)).foregroundStyle(ink)
            Text("Topic").dsText(DS.Text.bodyMdEmph, color: ink)
            Text("The company reported a 12% year-over-year revenue increase to $4.2 billion. This robust growth was driven by strong demand across all product segments and geographic regions.")
                .dsText(DS.Text.bodySm, color: ink)
        }
    }

    @ViewBuilder
    private func document(_ heading: String?, sub: String?) -> some View {
        VStack(alignment: .leading, spacing: DS.Space.sm) {
            if let heading { Text(heading).font(.custom(DS.Typeface.semibold, size: 18)).foregroundStyle(ink) }
            if let sub { Text(sub).dsText(DS.Text.bodyMdEmph, color: ink) }
            Text("The company reported a 12% year-over-year revenue increase to $4.2 billion. This robust growth was driven by strong demand across all product segments and geographic regions.")
                .dsText(DS.Text.bodySm, color: ink)
        }
    }
}
